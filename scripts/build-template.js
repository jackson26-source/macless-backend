#!/usr/bin/env node
// build-template.js — Workers have no filesystem at runtime, so the
// product template (the same files the desktop app copies onto a
// buyer's disk from its bundled template/ folder) has to be embedded
// directly into the Worker's JS bundle instead. This script walks
// ./template and emits src/lib/template-files.generated.js: a plain
// object mapping relative path -> file text.
//
// Run this whenever template/ changes, before `wrangler deploy`:
//   node scripts/build-template.js
//
// (A `npm run build:template` script wraps this — see package.json.)

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const TEMPLATE_DIR = path.join(__dirname, "..", "template");
const OUT_FILE = path.join(__dirname, "..", "src", "lib", "template-files.generated.js");

function walk(dir, base, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      walk(full, rel, out);
    } else if (entry.isFile()) {
      out[rel] = fs.readFileSync(full, "utf8");
    }
  }
  return out;
}

const files = walk(TEMPLATE_DIR, "", {});
const paths = Object.keys(files).sort();

const body =
  "// AUTO-GENERATED by scripts/build-template.js — do not hand-edit.\n" +
  "// Re-run that script after changing anything under template/.\n" +
  "// Source: macless-backend/template/ (" + paths.length + " files).\n\n" +
  "const TEMPLATE_FILES = " + JSON.stringify(files, null, 2) + ";\n\n" +
  "export { TEMPLATE_FILES };\n";

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, body);
console.log(`Wrote ${OUT_FILE} (${paths.length} files, ${Buffer.byteLength(body)} bytes)`);
